#!/usr/bin/env node
// The parity sample the coordinator audits against TradingView, generated from the extracts so
// no number is transcribed by hand. Part 1 is bar parity (the precondition in packet §13);
// Part 2 is rail read-back from the preserved captures; Part 3 is what a faithful port needs.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { etParts } from "../lib/bars.mjs";
import { sha256 } from "../lib/settings.mjs";

const OUT = fileURLToPath(new URL("../extracts/", import.meta.url));
const PAR = fileURLToPath(new URL("../parity/", import.meta.url));
mkdirSync(PAR, { recursive: true });
const manifest = JSON.parse(readFileSync(`${OUT}bars-manifest.json`, "utf8"));
const captures = JSON.parse(readFileSync(`${OUT}capture-audit.json`, "utf8"));
const PICKS = [["C", "4H"], ["ABNB", "1H"], ["XLU", "3H"], ["DLR", "1D"]];
const L = [];
const p = (s) => L.push(s);

p("# Trendoscope parity sample — coordinator spot audit (2026-09-24)");
p("");
p("Generated by `research/trendoscope/bin/parity-sample.mjs` from the committed extracts. Nothing was typed by hand.");
p("This session has no TradingView tools; you do. Read each line against the chart and mark it.");
p("");
p("## Part 1 — bar parity: does a TradingView candle equal the chart API bar?");
p("");
p("Packet §13: provider bars may only feed a batch replay once symbol/feed/session/adjustment parity");
p("is established against sampled TradingView reads. Set the chart to the stated timeframe, extended");
p("session ON, linear scale, and compare open/high/low/close at the stated bar open time.");
p("");
p("**The thing to check first is the bar boundary, not the price.** The chart API anchors intraday");
p("buckets to UTC; TradingView anchors them to the symbol's session start. Their ET open times below");
p("show where that agrees and where it cannot.");
p("");
for (const [symbol, tf] of PICKS) {
  const row = manifest.series.find((s) => s.symbol === symbol && s.timeframe === tf);
  const bars = JSON.parse(readFileSync(`${OUT}bars/${symbol}-${tf}.json`, "utf8")).bars.slice(-10);
  p(`### ${symbol} · ${tf} · ${row.provenance.price_basis} · anchor ${row.provenance.session_anchor} · ${row.bar_count} bars`);
  p(`ET open clock times present in this series: ${Object.keys(row.et_open_hours).join(", ")}`);
  p("");
  p("| bar open (UTC) | bar open (ET) | open | high | low | close |");
  p("|---|---|---|---|---|---|");
  for (const b of bars) {
    const e = etParts(b.t);
    p(`| ${new Date(b.t).toISOString().replace(".000Z", "Z")} | ${e.date} ${String(e.hour).padStart(2, "0")}:${String(e.minute).padStart(2, "0")} | ${b.o} | ${b.h} | ${b.l} | ${b.c} |`);
  }
  p("");
}
p("Mark each row: `epoch match Y/N`, `OHLC match Y/N`, and if N, the TradingView value you saw.");
p("");
p("## Part 2 — rail read-back from the preserved ACP captures");
p("");
p("Target chart `99awrQQB`, study `Kqm3pV` (SCINTILLA · ACP Diagonals · Continued Rails V2), BITSTAMP:BTCUSD.");
p("These are the line endpoints already resolved in the capture. Confirm each still reads the same, or");
p("note that the pattern has since been retired from the 20-pattern retained state (which is expected");
p("and is not an error).");
p("");
for (const a of captures.audits) {
  p(`### ${a.context.symbol} · resolution ${a.context.resolution} · captured ${a.captured_at} · file sha256 ${a.file_sha256.slice(0, 16)}…`);
  p("");
  p("| line id | role | p1 bar | p1 time (UTC) | p1 price | p2 bar | p2 time (UTC) | p2 price | slope/bar |");
  p("|---|---|---|---|---|---|---|---|---|");
  for (const g of a.geometry) {
    for (const [id, role, rail, slope] of [
      [g.upper_line_id, "upper", g.upper_rail, g.upper_slope_per_bar],
      [g.lower_line_id, "lower", g.lower_rail, g.lower_slope_per_bar]]) {
      const iso = (ms) => new Date(ms).toISOString().replace(".000Z", "Z");
      p(`| ${id} | ${role} | ${rail.p1_index} | ${iso(rail.p1_epoch)} | ${rail.p1_price} | ${rail.p2_index} | ${iso(rail.p2_epoch)} | ${rail.p2_price} | ${slope.toFixed(4)} |`);
    }
  }
  p("");
}
p("The per-endpoint indices, epochs and prices for all 48 resolved endpoints are in");
p("`research/trendoscope/extracts/capture-audit.json` (`audits[].geometry`), and the raw line");
p("primitives stay in the Indicator Lab's own evidence file, unmodified.");
p("");
p("## Part 3 — what a faithful replay still needs from you");
p("");
p("1. The source of the six Trendoscope Pine libraries the fork imports (see MISSING-DETECTOR-SOURCES.md).");
p("2. A detector-side export, per accepted pattern, at the bar `valid` first becomes true:");
p("   `patternName`, `zigzag lane` and recursion `level`, the ordered 5/6 pivots with");
p("   `{side, source bar index, epoch, price, is_synthetic}`, and both rails' `p1`/`p2` index, epoch and price.");
p("3. Confirmation that the saved instance is still V2 (`Kqm3pV`) and that retention is 20 with Avoid Overlap on.");
p("");
p("Without (1) and (2) the event packet in `research/trendoscope/lib/event.mjs` has a schema but no events.");

const body = L.join("\n") + "\n";
writeFileSync(`${PAR}PARITY-SAMPLE-20260924.md`, body);
console.log(`parity sample written: ${body.split("\n").length} lines, sha256 ${sha256(body).slice(0, 16)}…`);
