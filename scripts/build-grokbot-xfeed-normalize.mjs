#!/usr/bin/env node
/** GB1 · the grokbot-inbox edge function validates X posts with the X collector's own rules.
 *
 *  An edge function is bundled from supabase/functions/ only, and scripts/xfeed-ingest.mjs opens files (it is the
 *  offline importer), so the function cannot import it directly. This script cuts the PURE validators out of
 *  scripts/xfeed-ingest.mjs — everything from `const KINDS` to just before `function canonical` — and writes them,
 *  untouched, to supabase/functions/_shared/xfeed-normalize.mjs. tests/grokbot-inbox.test.mjs fails if the two
 *  drift, so there is one set of rules, not a copy that ages.
 *
 *  Run after any change to the validators in scripts/xfeed-ingest.mjs:  node scripts/build-grokbot-xfeed-normalize.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
export const SOURCE = join(root, 'scripts/xfeed-ingest.mjs');
export const TARGET = join(root, 'supabase/functions/_shared/xfeed-normalize.mjs');

export function build(source = readFileSync(SOURCE, 'utf8')) {
  const start = source.indexOf('\nconst KINDS = ');
  const end = source.indexOf('\nfunction canonical(');
  if (start < 0 || end < 0 || end <= start) throw new Error('scripts/xfeed-ingest.mjs no longer has the validator block this script cuts out');
  const body = source.slice(start + 1, end + 1);
  if (/\b(readFile|writeFile|appendFile|open|rename|unlink|mkdir|process)\b/.test(body)) throw new Error('the validator block is no longer pure: it touches files or the process');
  return '// GENERATED by scripts/build-grokbot-xfeed-normalize.mjs from scripts/xfeed-ingest.mjs — DO NOT EDIT HERE.\n' +
    '// The X collector\'s own validators (ids as strings, handles, ISO times with a zone, x.com addresses only),\n' +
    '// cut out unchanged so the grokbot-inbox edge function applies exactly the rules the collector applies.\n' +
    body;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(TARGET, build());
  process.stdout.write('wrote ' + TARGET + '\n');
}
